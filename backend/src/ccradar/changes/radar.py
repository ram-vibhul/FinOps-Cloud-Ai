PUBLIC_IPV4_HOUR = 0.005
Known = Callable[[str, str], dict[str, Any] | None]  # (resource type, id or name) -> attributes


@dataclass
class Impact:
    monthly: float  # change in monthly run rate; negative = saves
    currency: str
    source: str  # bill | list price
    label: str  # what was priced, e.g. "4 x m5.4xlarge"

    def to_dict(self) -> dict[str, Any]:
        return {**asdict(self), "monthly": round(self.monthly, 2)}


@functools.cache
def region_factors() -> dict[str, float]:
    """Each AWS region's on-demand price level against US East (11.5), generated by
    tools/aws_region_prices.py from AWS's public prices."""
    path = Path(__file__).resolve().parents[1] / "data" / "aws_region_factors.json"
    try:
        return dict(json.loads(path.read_text(encoding="utf-8"))["factors"])
    except (OSError, ValueError, KeyError):
        return {}


@dataclass
class Pricing:
    """Prices in US dollars for the estimator, and how to show the result."""

    currency: str = "USD"
    factor: float = 1.0  # units of ``currency`` per US dollar
    prices_usd: dict[str, float] | None = None  # the organisation's own hourly rates
    region: str | None = None  # the event's region, for list prices

    def impact(self, monthly_usd: float, source: str, label: str) -> Impact:
        if source == "list price" and self.region:
            # Built-in list prices are US East; the customer's own rates are already regional.
            monthly_usd *= region_factors().get(self.region, 1.0)
        return Impact(monthly_usd * self.factor, self.currency, source, label)


def pricing_for(db: Session, org_id: uuid.UUID, today: date | None = None) -> Pricing:
    """The organisation's own rates (from its bill) and display currency."""
    from ccradar.costs.fx import rate
    from ccradar.costs.unit_prices import bill_prices

    org = db.get(Organization, org_id)
    currency = (org.default_currency if org else None) or "USD"
    factor = 1.0
    if currency != "USD":
        found = rate(db, today or utcnow().date(), "USD", currency, org_id)
        if found is None:
            return Pricing()  # no exchange rate: list prices in US dollars
        factor = float(found)
    own = bill_prices(db, org_id)["prices"]
    return Pricing(currency, factor, {k: v / factor for k, v in own.items()})


def _items(value: Any) -> list[dict[str, Any]]:
    return list((value or {}).get("items") or []) if isinstance(value, dict) else []


def _hourly(kind: Any, p: Pricing) -> tuple[float, str] | None:
    return est.instance_hourly(str(kind or ""), p.prices_usd)


def _instances(ids: list[str], known: Known, p: Pricing, sign: int, verb: str) -> Impact | None:
    total, sources, types = 0.0, set(), []
    for instance_id in ids:
        attrs = known("ec2_instance", instance_id) or {}
        price = _hourly(attrs.get("instance_type"), p)
        if price is None:
            continue
        spot = est.SPOT_FACTOR if attrs.get("lifecycle") == "spot" else 1.0
        total += price[0] * est.HOURS * spot
        sources.add(price[1])
        types.append(str(attrs["instance_type"]))
    if not types:
        return None
    label = f"{verb} {len(types)} x {types[0]}" if len(set(types)) == 1 else f"{verb} {len(types)}"
    return p.impact(sign * total, "bill" if sources == {"bill"} else "list price", label)


def _run_instances(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    priced = est.PRICERS["aws_instance"](
        {"instance_type": req.get("instanceType")}, p.prices_usd or {}
    )
    if priced is None:
        return None
    count = len(_items(res.get("instancesSet"))) or int(
        req.get("maxCount") or req.get("minCount") or 1
    )
    spot = (req.get("instanceMarketOptions") or {}).get("marketType") == "spot"
    monthly = priced[0] * count * (est.SPOT_FACTOR if spot else 1.0)
    return p.impact(monthly, priced[1], f"{count} x {priced[2]}{' spot' if spot else ''}")


def _resize_instance(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    new_type = (req.get("instanceType") or {}).get("value")
    old = (known("ec2_instance", str(req.get("instanceId"))) or {}).get("instance_type")
    new, before = _hourly(new_type, p), _hourly(old, p)
    if new is None or before is None:
        return None
    source = "bill" if new[1] == before[1] == "bill" else "list price"
    return p.impact((new[0] - before[0]) * est.HOURS, source, f"{old} -> {new_type}")


def _volume(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    priced = est.PRICERS["aws_ebs_volume"](
        {"type": req.get("volumeType"), "size": req.get("size")}, p.prices_usd or {}
    )
    return p.impact(priced[0], priced[1], priced[2]) if priced and priced[0] else None


def _old_volume(known: Known, volume_id: Any) -> float | None:
    attrs = known("ebs_volume", str(volume_id))
    if not attrs or not attrs.get("size_gb"):
        return None
    return float(attrs["size_gb"]) * est.EBS_GB_MONTH.get(attrs.get("volume_type") or "gp3", 0.08)


def _delete_volume(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    old = _old_volume(known, req.get("volumeId"))
    return p.impact(-old, "list price", "volume deleted") if old else None


def _modify_volume(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    old = _old_volume(known, req.get("volumeId"))
    attrs = known("ebs_volume", str(req.get("volumeId"))) or {}
    size = req.get("size") or attrs.get("size_gb")
    vtype = req.get("volumeType") or attrs.get("volume_type") or "gp3"
    if old is None or not size:
        return None
    new = float(size) * est.EBS_GB_MONTH.get(vtype, 0.08)
    return p.impact(new - old, "list price", f"volume now {float(size):g} GB {vtype}")


def _database(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    priced = est.PRICERS["aws_db_instance"](
        {
            "instance_class": req.get("dBInstanceClass"),
            "multi_az": req.get("multiAZ"),
            "allocated_storage": req.get("allocatedStorage"),
            "storage_type": req.get("storageType"),
        },
        p.prices_usd or {},
    )
    return p.impact(priced[0], priced[1], priced[2]) if priced else None


def _known_database(known: Known, name: Any, p: Pricing) -> tuple[float, str, dict] | None:
    attrs = known("rds_instance", str(name))
    price = _hourly((attrs or {}).get("instance_class"), p)
    if not attrs or price is None:
        return None
    az = est.MULTI_AZ if attrs.get("multi_az") else 1.0
    return price[0] * est.HOURS * az, price[1], attrs


def _delete_database(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    old = _known_database(known, req.get("dBInstanceIdentifier"), p)
    return p.impact(-old[0], old[1], f"{old[2]['instance_class']} deleted") if old else None


def _modify_database(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    old = _known_database(known, req.get("dBInstanceIdentifier"), p)
    if old is None or not (req.get("dBInstanceClass") or "multiAZ" in req):
        return None
    new_class = req.get("dBInstanceClass") or old[2]["instance_class"]
    multi = req["multiAZ"] if "multiAZ" in req else old[2].get("multi_az")
    price = _hourly(new_class, p)
    if price is None:
        return None
    new = price[0] * est.HOURS * (est.MULTI_AZ if multi else 1.0)
    label = f"{old[2]['instance_class']} -> {new_class}{' multi-AZ' if multi else ''}"
    return p.impact(new - old[0], price[1] if price[1] == old[1] else "list price", label)


def _fixed(monthly_usd: float, label: str) -> Callable[..., Impact | None]:
    return lambda req, res, known, p: p.impact(monthly_usd, "list price", label)


def _load_balancer(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    priced = est.PRICERS["aws_lb"]({"load_balancer_type": req.get("type")}, {})
    return p.impact(priced[0], priced[1], f"{req.get('type') or 'application'} load balancer")


def _delete_load_balancer(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    attrs = known("load_balancer", str(req.get("loadBalancerArn"))) or {}
    priced = est.PRICERS["aws_lb"]({"load_balancer_type": attrs.get("type")}, {})
    return p.impact(-priced[0], priced[1], "load balancer deleted")


def _cache(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    priced = est.PRICERS["aws_elasticache_cluster"](
        {"node_type": req.get("cacheNodeType"), "num_cache_nodes": req.get("numCacheNodes")},
        p.prices_usd or {},
    )
    return p.impact(priced[0], priced[1], priced[2]) if priced else None


def _node_group(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    priced = est.PRICERS["aws_eks_node_group"](
        {
            "instance_types": req.get("instanceTypes"),
            "scaling_config": [
                {"desired_size": (req.get("scalingConfig") or {}).get("desiredSize")}
            ],
            "capacity_type": req.get("capacityType"),
        },
        p.prices_usd or {},
    )
    return p.impact(priced[0], priced[1], priced[2]) if priced else None


def _asg_mix(attrs: dict[str, Any]) -> float:
    """Share of the on-demand price paid, given the group's on-demand percentage."""
    od = float(attrs.get("on_demand_pct", 100) or 0) / 100
    return od + (1 - od) * est.SPOT_FACTOR


def _asg_capacity(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    """UpdateAutoScalingGroup / SetDesiredCapacity: the change in running servers (10.3)."""
    attrs = known("autoscaling_group", str(req.get("autoScalingGroupName"))) or {}
    old = attrs.get("desired")
    types = attrs.get("instance_types") or []
    if old is None or not types:
        return None
    new = req.get("desiredCapacity")
    if new is None and req.get("minSize") is not None and int(req["minSize"]) > int(old):
        new = req["minSize"]
    if new is None and req.get("maxSize") is not None and int(req["maxSize"]) < int(old):
        new = req["maxSize"]
    if new is None or int(new) == int(old):
        return None
    price = _hourly(types[0], p)
    if price is None:
        return None
    delta = (int(new) - int(old)) * price[0] * est.HOURS * _asg_mix(attrs)
    return p.impact(delta, price[1], f"{old} -> {new} x {types[0]}")


def _redshift_monthly(node_type: Any, nodes: Any) -> float | None:
    hourly = est.REDSHIFT_NODE_HOUR.get(str(node_type or ""))
    return None if hourly is None else hourly * int(nodes or 1) * est.HOURS


def _redshift_create(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    nodes = req.get("numberOfNodes") or 1
    monthly = _redshift_monthly(req.get("nodeType"), nodes)
    return (
        p.impact(monthly, "list price", f"{nodes} x {req.get('nodeType')} Redshift")
        if monthly
        else None
    )


def _redshift_old(req: dict, known: Known) -> tuple[float, dict[str, Any]] | None:
    attrs = known("redshift_cluster", str(req.get("clusterIdentifier")))
    monthly = _redshift_monthly((attrs or {}).get("node_type"), (attrs or {}).get("nodes"))
    return (monthly, attrs or {}) if monthly else None


def _redshift_resize(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
    old = _redshift_old(req, known)
    if old is None or not (req.get("nodeType") or req.get("numberOfNodes")):
        return None
    node_type = req.get("nodeType") or old[1].get("node_type")
    nodes = req.get("numberOfNodes") or old[1].get("nodes")
    new = _redshift_monthly(node_type, nodes)
    if new is None:
        return None
    label = f"{old[1].get('nodes')} x {old[1].get('node_type')} -> {nodes} x {node_type}"
    return p.impact(new - old[0], "list price", label)


def _redshift_gone(verb: str, sign: int) -> Callable[..., Impact | None]:
    def handler(req: dict, res: dict, known: Known, p: Pricing) -> Impact | None:
        old = _redshift_old(req, known)
        return p.impact(sign * old[0], "list price", f"Redshift {verb}") if old else None

    return handler


def _ids(req: dict) -> list[str]:
    return [
        str(i.get("instanceId")) for i in _items(req.get("instancesSet")) if i.get("instanceId")
    ]


NAT = est.NAT_HOUR * est.HOURS
IP = PUBLIC_IPV4_HOUR * est.HOURS
HANDLERS: dict[tuple[str, str], Callable[[dict, dict, Known, Pricing], Impact | None]] = {
    ("ec2", "RunInstances"): _run_instances,
    ("ec2", "TerminateInstances"): lambda q, r, k, p: _instances(_ids(q), k, p, -1, "terminated"),
    ("ec2", "StopInstances"): lambda q, r, k, p: _instances(_ids(q), k, p, -1, "stopped"),
    ("ec2", "StartInstances"): lambda q, r, k, p: _instances(_ids(q), k, p, 1, "started"),
    ("ec2", "ModifyInstanceAttribute"): _resize_instance,
    ("ec2", "CreateVolume"): _volume,
    ("ec2", "DeleteVolume"): _delete_volume,
    ("ec2", "ModifyVolume"): _modify_volume,
    ("ec2", "CreateNatGateway"): _fixed(NAT, "NAT gateway (data processed is extra)"),
    ("ec2", "DeleteNatGateway"): _fixed(-NAT, "NAT gateway deleted"),
    ("ec2", "AllocateAddress"): _fixed(IP, "public IPv4 address"),
    ("ec2", "ReleaseAddress"): _fixed(-IP, "public IPv4 address released"),
    ("rds", "CreateDBInstance"): _database,
    ("rds", "DeleteDBInstance"): _delete_database,
    ("rds", "ModifyDBInstance"): _modify_database,
    ("elasticloadbalancing", "CreateLoadBalancer"): _load_balancer,
    ("elasticloadbalancing", "DeleteLoadBalancer"): _delete_load_balancer,
    ("elasticache", "CreateCacheCluster"): _cache,
    ("eks", "CreateNodegroup"): _node_group,
    ("eks", "CreateCluster"): _fixed(est.EKS_CLUSTER_HOUR * est.HOURS, "EKS control plane"),
    ("autoscaling", "UpdateAutoScalingGroup"): _asg_capacity,  # 10.3
    ("autoscaling", "SetDesiredCapacity"): _asg_capacity,
    ("redshift", "CreateCluster"): _redshift_create,
    ("redshift", "ResizeCluster"): _redshift_resize,
    ("redshift", "ModifyCluster"): _redshift_resize,
    ("redshift", "DeleteCluster"): _redshift_gone("deleted", -1),
    ("redshift", "PauseCluster"): _redshift_gone("paused (storage still billed)", -1),
    ("redshift", "ResumeCluster"): _redshift_gone("resumed", 1),
}


def assess(detail: dict[str, Any], known: Known, pricing: Pricing) -> Impact | None:
    """Price one CloudTrail event (its parsed ``CloudTrailEvent`` record), or None when the
    event failed, changes nothing we can price, or lacks what is needed."""
    if detail.get("errorCode"):
        return None  # the call was refused: nothing changed
    service = str(detail.get("eventSource") or "").split(".", 1)[0]
    handler = HANDLERS.get((service, str(detail.get("eventName") or "")))
    if handler is None:
        return None
    pricing = dataclasses.replace(pricing, region=detail.get("awsRegion") or pricing.region)
    try:
        impact = handler(
            detail.get("requestParameters") or {},
            detail.get("responseElements") or {},
            known,
            pricing,
        )
    except (TypeError, ValueError, KeyError, AttributeError):
        return None  # an unexpected event shape must never stop the import
    return impact if impact is not None and abs(impact.monthly) >= 0.01 else None


def inventory_lookup(db: Session) -> Known:
    """Last known configuration of resources in the current organisation, loaded once per
    resource type for the whole scan (11.15) instead of one query per event."""
    cache: dict[str, dict[str, dict[str, Any]]] = {}

    def known(resource_type: str, key: str) -> dict[str, Any] | None:
        if not key or key == "None":
            return None
        if resource_type not in cache:
            by_key: dict[str, dict[str, Any]] = {}
            rows = db.execute(
                select(
                    CloudResource.resource_id, CloudResource.name, CloudResource.attributes
                ).where(CloudResource.resource_type == resource_type)
            ).all()
            for resource_id, name, attributes in rows:
                by_key[resource_id] = dict(attributes or {})
                if name:
                    by_key.setdefault(name, dict(attributes or {}))
            cache[resource_type] = by_key
        return cache[resource_type].get(key)

    return known


def _utc(when: datetime) -> datetime:
    """SQLite returns times without a zone; they are UTC."""
    return when if when.tzinfo else when.replace(tzinfo=UTC)


def short_actor(actor: str | None) -> str:
    """ "arn:aws:sts::1:assumed-role/Admin/ravi" -> "ravi"."""
    if not actor:
        return "Someone"
    return actor.rsplit("/", 1)[-1].rsplit(":", 1)[-1] or actor


def feed(
    db: Session, org_id: uuid.UUID, hours: int = 24, now: datetime | None = None
) -> dict[str, Any]:
    """Priced changes of the last ``hours`` hours, newest first, with totals. A change is
    "not in the bill yet" until billing data exists for a day after it happened (the
    day of the change itself is only partly billed)."""
    now = now or utcnow()
    org = db.get(Organization, org_id)
    billed_through = latest_date(db, org_id)
    events = db.scalars(
        select(ChangeEvent)
        .where(ChangeEvent.occurred_at >= now - timedelta(hours=hours))
        .order_by(ChangeEvent.occurred_at.desc())
        .limit(500)
    ).all()
    items, added, removed, pending, unpriced = [], 0.0, 0.0, 0.0, 0
    for e in events:
        impact = (e.attributes or {}).get("impact")
        if e.source == "cloudtrail" and not impact:
            unpriced += 1
        if not impact:
            continue
        monthly = float(impact["monthly"])
        in_bill = billed_through is not None and _utc(e.occurred_at).date() < billed_through
        added += max(monthly, 0.0)
        removed += min(monthly, 0.0)
        pending += 0.0 if in_bill else monthly
        items.append(
            {
                "id": str(e.id),
                "occurred_at": _utc(e.occurred_at).isoformat(),
                "title": e.title,
                "actor": short_actor(e.actor),
                "account": e.account,
                "region": e.region,
                "service": e.service,
                "monthly": round(monthly, 2),
                "label": impact.get("label"),
                "source": impact.get("source"),
                "in_bill": in_bill,
                "expected": (e.attributes or {}).get("expected"),
                "measured": (e.attributes or {}).get("measured"),  # 11.27
                "policy": (e.attributes or {}).get("policy") or [],  # 11.41
                "undo": undo(
                    str((e.attributes or {}).get("event_name") or ""),
                    e.resource_id,
                    e.region,
                    monthly,
                    impact.get("label"),
                    str((e.attributes or {}).get("event_source") or ""),
                ),
            }
        )
    currency = (org.default_currency if org else None) or "USD"
    scans = []
    for conn in db.scalars(
        select(CloudConnection).where(
            CloudConnection.provider.in_(("aws", "azure", "gcp")),
            CloudConnection.status == "active",
        )
    ):
        scan = (conn.settings or {}).get("radar_scan")
        if scan:
            scans.append(
                {
                    "connection": conn.name,
                    "at": scan.get("at"),
                    "complete": bool(scan.get("complete")),
                    "problems": scan.get("problems") or [],
                }
            )
    return {
        "currency": currency,
        "hours": hours,
        "scans": scans,
        "billed_through": billed_through.isoformat() if billed_through else None,
        "added_monthly": round(added, 2),
        "removed_monthly": round(removed, 2),
        "net_monthly": round(added + removed, 2),
        "not_in_bill_monthly": round(pending, 2),
        "unpriced": unpriced,
        "accuracy": accuracy(db),
        "items": items,
    }


def alert(db: Session, org_id: uuid.UUID, events: list[ChangeEvent]) -> int:
    """Tell people about newly seen changes that add more than the organisation's
    threshold to the monthly run rate. Each change is alerted once (when first seen)."""
    from ccradar.core.notify import Message, notify
    from ccradar.costs.anomalies import alert_settings

    org = db.get(Organization, org_id)
    if org is None:
        return 0
    from ccradar.changes.guardrails import warnings

    guard = warnings(db, org_id, events, utcnow().date())  # 11.33, even with Radar alerts off
    if guard:
        notify(db, "budget_alert", guard)
    breaches = [
        Message(
            title=f"{short_actor(e.actor)} broke policy {hit['policy']}: {e.title}"[:200],
            text=f"{hit['detail']}{' in ' + e.region if e.region else ''}. "
            "Found in the change itself, minutes after it was made.",
            link=f"/radar?change={e.id}",
            severity="alert",
        )
        for e in events
        for hit in (e.attributes or {}).get("policy") or []
    ]
    if breaches:  # 11.41
        notify(db, "policy_violation", breaches[:10])
    cfg = alert_settings(org)
    if not cfg.radar_alerts:
        return 0
    costly = sorted(
        (
            e
            for e in events
            if float(((e.attributes or {}).get("impact") or {}).get("monthly", 0))
            >= cfg.radar_min_monthly
        ),
        key=lambda e: -float(e.attributes["impact"]["monthly"]),
    )
    messages = []
    for e in costly[:5]:
        impact = e.attributes["impact"]
        where = ", ".join(x for x in (e.region, f"account {e.account}" if e.account else None) if x)
        messages.append(
            Message(
                title=(
                    f"{short_actor(e.actor)} added about {impact['monthly']:,.0f} "
                    f"{impact['currency']} a month: {impact['label']}"
                )[:200],
                text=(
                    f"{e.title}{' in ' + where if where else ''}, "
                    f"{e.occurred_at:%d %b %H:%M} UTC.\n"
                    "This is not in your bill yet; it is priced from "
                    f"{'your own rates' if impact['source'] == 'bill' else 'list prices'}."
                ),
                link=f"/radar?change={e.id}",
                actions=[("Mark as expected", f"/radar?change={e.id}&expected=1")],
            )
        )
    if len(costly) > 5:
        rest = sum(float(e.attributes["impact"]["monthly"]) for e in costly[5:])
        messages.append(
            Message(
                title=f"{len(costly) - 5} more costly changes: about {rest:,.0f} a month",
                text="Open the Radar to see them all.",
                link="/radar",
            )
        )
    if messages:
        notify(db, "live_change", messages)
    return len(costly)
