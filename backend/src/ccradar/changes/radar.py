"""Live Radar (10.1): the cost of a change, minutes after it is made.

Billing data arrives 24 to 48 hours late, so a tool that only reads the bill tells you
about an expensive mistake two days after it started costing money. CloudCostRadar already
reads the account's change events (CloudTrail, read-only); this module prices each one
from what the event itself says (instance type and count, disk size, database class…),
using the organisation's own hourly rates from its bill where it has them and list
prices otherwise. Deletions and resizes are priced from the inventory's last known
configuration of the resource.

The result is a monthly run-rate change (positive = costs more), stored on the change
event, shown on the Radar page, and alerted when it passes the organisation's threshold.
It is an estimate made before the bill; the timeline later shows the measured effect."""

