#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES.md from installed runtime dependencies.

Python: walks the runtime dependency closure of the ``ccradar`` distribution in
the active environment (dev-only tools are excluded).
JavaScript: walks the production dependency closure of frontend/package.json
using frontend/node_modules.

    backend/.venv/bin/python tools/third_party_notices.py          # write file
    backend/.venv/bin/python tools/third_party_notices.py --check  # CI: fail on
        disallowed licences or when the committed file is stale
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "THIRD_PARTY_NOTICES.md"

# Strong copyleft licences are incompatible with closed-source distribution.
DISALLOWED = re.compile(r"\b(A?GPL|SSPL|BUSL|Commons Clause|CC-BY-NC)\b", re.IGNORECASE)
# Weak copyleft is acceptable when used unmodified as a separate library.
REVIEWED_WEAK_COPYLEFT = {"psycopg", "psycopg-binary", "psycopg-pool"}

CLASSIFIER_MAP = {
    "MIT License": "MIT",
    "BSD License": "BSD",
    "Apache Software License": "Apache-2.0",
    "ISC License (ISCL)": "ISC",
    "Python Software Foundation License": "PSF-2.0",
    "Mozilla Public License 2.0 (MPL 2.0)": "MPL-2.0",
    "GNU Lesser General Public License v3 (LGPLv3)": "LGPL-3.0",
}


def python_licence(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    expr = meta.get("License-Expression")
    if expr:
        return expr
    classifiers = [
        c.split(" :: ")[-1] for c in meta.get_all("Classifier") or [] if c.startswith("License ::")
    ]
    mapped = [CLASSIFIER_MAP.get(c, c) for c in classifiers if c != "OSI Approved"]
    if mapped:
        return " OR ".join(dict.fromkeys(mapped))
    raw = (meta.get("License") or "").strip().splitlines()
    return raw[0][:60] if raw else "UNKNOWN"


def python_packages(root: str = "ccradar") -> list[tuple[str, str, str]]:
    seen: dict[str, metadata.Distribution] = {}
    stack = [(root, frozenset[str]())]
    while stack:
        name, extras = stack.pop()
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        key = dist.metadata["Name"].lower().replace("_", "-")
        if key in seen and not extras:
            continue
        seen[key] = dist
        for raw in dist.requires or []:
            req = Requirement(raw)
            envs = [{"extra": e} for e in extras] or [{"extra": ""}]
            if req.marker and not any(req.marker.evaluate(env) for env in envs):
                continue
            if key == root and req.marker and "extra" in str(req.marker):
                continue  # skip ccradar[dev]
            stack.append((req.name, frozenset(req.extras)))
    seen.pop(root, None)
    return sorted(
        (d.metadata["Name"], d.version, python_licence(d)) for d in seen.values()
    )


def js_packages() -> list[tuple[str, str, str]]:
    frontend = ROOT / "frontend"
    modules = frontend / "node_modules"
    pkg = json.loads((frontend / "package.json").read_text())
    result: dict[str, tuple[str, str, str]] = {}
    stack = list(pkg.get("dependencies", {}))
    while stack:
        name = stack.pop()
        if name in result:
            continue
        manifest = modules / name / "package.json"
        if not manifest.exists():
            continue
        data = json.loads(manifest.read_text())
        lic = data.get("license") or "UNKNOWN"
        if isinstance(lic, dict):
            lic = lic.get("type", "UNKNOWN")
        result[name] = (name, data.get("version", "?"), str(lic))
        stack.extend(data.get("dependencies", {}))
    return sorted(result.values())


def render(py: list[tuple[str, str, str]], js: list[tuple[str, str, str]]) -> str:
    lines = [
        "# Third-party notices",
        "",
        "CloudCostRadar includes the open-source components listed below. Each is",
        "distributed under its own licence; the full licence texts are included",
        "with each package (Python: `*.dist-info/`, JavaScript: the package folder)",
        "and are available from the project homepages.",
        "",
        "This file is generated by `tools/third_party_notices.py`; do not edit by hand.",
        "",
        "## Python (server)",
        "",
        "| Package | Version | Licence |",
        "|---|---|---|",
        *(f"| {n} | {v} | {lic} |" for n, v, lic in py),
        "",
        "## JavaScript (web UI, bundled)",
        "",
        "| Package | Version | Licence |",
        "|---|---|---|",
        *(f"| {n} | {v} | {lic} |" for n, v, lic in js),
        "",
    ]
    return "\n".join(lines)


def problems(rows: list[tuple[str, str, str]]) -> list[str]:
    out = []
    for name, version, lic in rows:
        if name.lower() in REVIEWED_WEAK_COPYLEFT:
            continue
        if lic == "UNKNOWN" or (DISALLOWED.search(lic) and "LGPL" not in lic.upper()):
            out.append(f"{name} {version}: {lic}")
    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    py, js = python_packages(), js_packages()
    text = render(py, js)
    bad = problems(py + js)
    if bad:
        print("Licences needing review:\n  " + "\n  ".join(bad), file=sys.stderr)
    if args.check:
        stale = not OUTPUT.exists() or OUTPUT.read_text() != text
        if stale:
            print("THIRD_PARTY_NOTICES.md is out of date; regenerate it.", file=sys.stderr)
        return 1 if bad or stale else 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(py)} Python, {len(js)} JavaScript packages")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
