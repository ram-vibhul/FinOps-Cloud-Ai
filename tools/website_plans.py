#!/usr/bin/env python3
"""Write the plans table on website/pricing.html from the plan catalogue (B.9), so the
website and the product never disagree.

    backend/.venv/bin/python tools/website_plans.py          # rewrite the table
    backend/.venv/bin/python tools/website_plans.py --check  # fail when it is stale
"""

from __future__ import annotations

import argparse
import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOGUE = ROOT / "backend/src/ccradar/billing/plans.json"
PAGE = ROOT / "website/pricing.html"
BEGIN = (
    "<!-- BEGIN PLANS (generated by tools/website_plans.py from "
    "backend/src/ccradar/billing/plans.json) -->"
)
END = "<!-- END PLANS -->"
# Same words as the product (billing/plans.py FEATURES and LIMITS).
FEATURES = {
    "kubernetes": "Kubernetes clusters",
    "ai": "AI explanations and questions in plain words",
    "api_keys": "API keys",
    "webhooks_out": "Outgoing webhooks",
    "work_integrations": "Tickets and pull requests",
    "sso": "Single sign-on",
    "scim": "User provisioning (SCIM)",
    "custom_roles": "Custom roles",
    "mcp": "AI assistant access (MCP)",
    "auto_fixes": "Automatic fixes",
    "partner": "Partner portfolio",
}
LIMITS = {
    "members": "People",
    "connections": "Cloud and SaaS connections",
    "clusters": "Kubernetes clusters",
    "cloud_spend_monthly_usd": "Cloud spend under management (USD a month)",
    "retention_days": "Longest data retention (days)",
    "api_calls_daily": "API calls a day",
    "ai_summaries_monthly": "AI summaries a month",
}


def table(catalogue: dict) -> str:
    plans = catalogue["plans"]
    head = "".join(f'<th scope="col">{html.escape(p["name"])}</th>' for p in plans)
    rows = []
    for key, label in LIMITS.items():
        cells = []
        for p in plans:
            value = p.get("limits", {}).get(key)
            cells.append(f"<td>{'Unlimited' if value is None else f'{value:,}'}</td>")
        rows.append(f'<tr><th scope="row">{label}</th>{"".join(cells)}</tr>')
    for key, label in FEATURES.items():
        cells = "".join(
            f"<td>{'Included' if key in p.get('features', []) else '—'}</td>"
            for p in plans
        )
        rows.append(f'<tr><th scope="row">{label}</th>{cells}</tr>')
    body = "\n          ".join(rows)
    corner = '<th scope="col"><span class="skip">Feature</span></th>'
    return (
        f'{BEGIN}\n    <div class="table-wrap">\n      <table>\n'
        f"        <thead><tr>{corner}{head}</tr></thead>\n"
        f"        <tbody>\n          {body}\n        </tbody>\n"
        f"      </table>\n    </div>\n    {END}"
    )


def render(page: str, catalogue: dict) -> str:
    start, end = page.index(BEGIN), page.index(END) + len(END)
    return page[:start] + table(catalogue) + page[end:]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    catalogue = json.loads(CATALOGUE.read_text(encoding="utf-8"))
    unknown = {
        k
        for p in catalogue["plans"]
        for k in [*p.get("features", []), *p.get("limits", {})]
        if k not in FEATURES and k not in LIMITS
    }
    if unknown:
        print(
            f"add these to tools/website_plans.py: {sorted(unknown)}", file=sys.stderr
        )
        return 1
    page = PAGE.read_text(encoding="utf-8")
    wanted = render(page, catalogue)
    if args.check:
        if wanted != page:
            print(
                "website/pricing.html is stale: run tools/website_plans.py",
                file=sys.stderr,
            )
            return 1
        return 0
    PAGE.write_text(wanted, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
